using System;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace FlecsCodeGenerator;

class Program
{
    static int Main(string[] args)
    {
        string inputPath = args.Length > 0 ? args[0] : "D:\\GitKraken\\GodotFlecs3D\\sources\\Flecs\\Components\\ComponentsFlecs.cs";
        string outputPath = args.Length > 1 ? args[1] : "D:\\GitKraken\\GodotFlecs3D\\sources\\Flecs\\Components\\GeneratedFlecsRegistry.cs";

        if (!File.Exists(inputPath))
        {
            Console.WriteLine($"❌ No se encontró el archivo de componentes en: {Path.GetFullPath(inputPath)}");
            Console.WriteLine("Uso: dotnet run -- <ruta_entrada.cs> <ruta_salida.cs>");
            return 1;
        }

        try
        {
            string sourceCode = File.ReadAllText(inputPath);
            SyntaxTree tree = CSharpSyntaxTree.ParseText(sourceCode);
            var root = tree.GetRoot();

            string generatedCode = BuildRegistryCode(root);

            string fullOutputPath = Path.GetFullPath(outputPath);
            Directory.CreateDirectory(Path.GetDirectoryName(fullOutputPath)!);
            File.WriteAllText(fullOutputPath, generatedCode);

            Console.WriteLine($"✅ ¡Registro de Flecs generado con éxito en: {fullOutputPath}");
            return 0;
        }
        catch (Exception ex)
        {
            Console.WriteLine($"❌ Error durante la generación del código: {ex.Message}");
            return 1;
        }
    }

    private static string BuildRegistryCode(SyntaxNode root)
    {
        var writer = new StringWriter();

        WriteHeader(writer);
        writer.WriteLine("public static class GeneratedFlecsRegistry");
        writer.WriteLine("{");
        writer.WriteLine("    public static void Build(World world)");
        writer.WriteLine("    {");

        // 1. Registrar Enums
        AppendEnumRegistrations(writer, root);

        // 2. Registrar Tipos especiales de Godot
        AppendGodotTypesRegistration(writer);

        // 3. Registrar tus Componentes personalizados del archivo
        AppendComponentRegistrations(writer, root);

        writer.WriteLine("    }");
        writer.WriteLine("}");

        return writer.ToString();
    }

    private static void WriteHeader(StringWriter writer)
    {
        writer.WriteLine("//------------------------------------------------------------------------------");
        writer.WriteLine("// <auto-generated>");
        writer.WriteLine("//     Este código fue generado automáticamente por FlecsCodeGenerator.");
        writer.WriteLine("//     Los cambios manuales en este archivo se perderán si se vuelve a generar.");
        writer.WriteLine("// </auto-generated>");
        writer.WriteLine("//------------------------------------------------------------------------------");
        writer.WriteLine();
        writer.WriteLine("using Flecs.NET.Core;");
        writer.WriteLine("using Godot;");
        writer.WriteLine("using GodotEcsArch.sources.components;");
        writer.WriteLine("using GodotEcsArch.sources.managers.Characters;");
        writer.WriteLine("using GodotFlecs.sources.Flecs.Components;");
        writer.WriteLine();

        writer.WriteLine("namespace GodotFlecs.sources.Flecs;");
        writer.WriteLine();
    }
    /// <summary>
    /// Registra explícitamente los tipos externos/Godot más comunes para que puedan ser usados dentro de los componentes.
    /// </summary>
    private static void AppendGodotTypesRegistration(StringWriter writer)
    {
        writer.WriteLine("        // ===========================================");
        writer.WriteLine("        // Registro de Tipos Nativos / Godot");
        writer.WriteLine("        // ===========================================");

        // Vector2
        writer.WriteLine("        world.Component<Vector2>()");
        writer.WriteLine("            .Member<float>(\"X\")");
        writer.WriteLine("            .Member<float>(\"Y\");");
        writer.WriteLine();

        // Vector2I
        writer.WriteLine("        world.Component<Vector2I>()");
        writer.WriteLine("            .Member<int>(\"X\")");
        writer.WriteLine("            .Member<int>(\"Y\");");
        writer.WriteLine();

        // Vector3
        writer.WriteLine("        world.Component<Vector3>()");
        writer.WriteLine("            .Member<float>(\"X\")");
        writer.WriteLine("            .Member<float>(\"Y\")");
        writer.WriteLine("            .Member<float>(\"Z\");");
        writer.WriteLine();

        // Color
        writer.WriteLine("        world.Component<Color>()");
        writer.WriteLine("            .Member<float>(\"R\")");
        writer.WriteLine("            .Member<float>(\"G\")");
        writer.WriteLine("            .Member<float>(\"B\")");
        writer.WriteLine("            .Member<float>(\"A\");");
        writer.WriteLine();

        // Rect2 (Usa Vector2, por lo que Vector2 debe estar registrado antes)
        writer.WriteLine("        world.Component<Rect2>()");
        writer.WriteLine("            .Member<Vector2>(\"Position\")");
        writer.WriteLine("            .Member<Vector2>(\"Size\");");
        writer.WriteLine();
        
        // Rid
        writer.WriteLine("        world.Component<Rid>()");
        writer.WriteLine("            .Member<ulong>(\"Id\");");
        writer.WriteLine();
    }
    private static void AppendEnumRegistrations(StringWriter writer, SyntaxNode root)
    {
        var enums = root.DescendantNodes().OfType<EnumDeclarationSyntax>();

        foreach (var enm in enums)
        {
            string enumName = enm.Identifier.Text;
            writer.WriteLine($"        // Registro de Enum: {enumName}");
            writer.WriteLine($"        var {enumName.ToLower()}Comp = world.Component<{enumName}>();");

            int currentValue = 0; // 🔹 Contador para el autoincremento de enums

            foreach (var member in enm.Members)
            {
                string memberName = member.Identifier.Text;

                if (member.EqualsValue != null)
                {
                    string rawVal = member.EqualsValue.Value.ToString().Trim();
                    // Intentamos parsear si es un número entero para sincronizar el autoincremento futuro
                    if (int.TryParse(rawVal, out int parsedVal))
                    {
                        currentValue = parsedVal;
                    }
                    writer.WriteLine($"        {enumName.ToLower()}Comp.Constant(\"{memberName}\", ({enumName})({rawVal}));");
                }
                else
                {
                    writer.WriteLine($"        {enumName.ToLower()}Comp.Constant(\"{memberName}\", ({enumName})({currentValue}));");
                }

                currentValue++; // Incrementa automáticamente para el siguiente miembro
            }
            writer.WriteLine();
        }
    }

    private static void AppendComponentRegistrations(StringWriter writer, SyntaxNode root)
    {
        // 🔹 MODIFICADO: Selecciona todos los structs y record structs sin requerir ningún atributo
        var structs = root.DescendantNodes()
            .OfType<TypeDeclarationSyntax>()
            .Where(s => s.IsKind(SyntaxKind.StructDeclaration) || s.IsKind(SyntaxKind.RecordStructDeclaration));

        foreach (var st in structs)
        {
            string structName = st.Identifier.Text;
            writer.WriteLine($"        // Registro de Componente: {structName}");
            writer.WriteLine($"        world.Component<{structName}>()");

            // 1. Procesar Propiedades automáticas
            foreach (var prop in st.Members.OfType<PropertyDeclarationSyntax>())
            {
                AppendMember(writer, prop.Type.ToString(), prop.Identifier.Text);
            }

            // 2. Procesar Campos tradicionales
            foreach (var field in st.Members.OfType<FieldDeclarationSyntax>())
            {
                string fieldType = field.Declaration.Type.ToString();
                foreach (var variable in field.Declaration.Variables)
                {
                    AppendMember(writer, fieldType, variable.Identifier.Text);
                }
            }

            // 3. Procesar Primary Constructors en Record Structs
            if (st.ParameterList != null)
            {
                foreach (var param in st.ParameterList.Parameters)
                {
                    string paramName = param.Identifier.Text;
                    string paramType = param.Type?.ToString() ?? "float";
                    string memberName = char.ToUpper(paramName[0]) + paramName.Substring(1);
                    AppendMember(writer, paramType, memberName);
                }
            }

            writer.WriteLine("            ;");
            writer.WriteLine();
        }
    }

    private static void AppendMember(StringWriter writer, string type, string name)
    {
        if (type == "Entity" || type == "ulong")
        {
            writer.WriteLine($"            .Member(Ecs.Entity, \"{name}\")");
        }
        else
        {
            writer.WriteLine($"            .Member<{type}>(\"{name}\")");
        }
    }
}